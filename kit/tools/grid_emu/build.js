#!/usr/bin/env node
'use strict';
/**
 * build.js - The Grid's emulator: one self-contained web page that runs the app's own code (the
 * staged build in dist/the_grid, the same files the Store builds on the car) in the browser, drawn
 * by the car's GPU draw engine (WebAssembly), with the cluster and HUD drawn from what the app
 * sends cluster-render, and a simulated X4 M behind it.
 *
 *   npm i --no-save esbuild pako buffer events path-browserify     (once; or NODE_PATH to them)
 *   node kit/tools/grid_emu/build.js [out.html]                     -> dist/grid-emu/index.html
 *
 * Nothing here goes into the app or the car: it is a preview tool. The page is not installable.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..', '..');
const HERE = __dirname;
const WEB = path.join(HERE, 'web');
const GEN = path.join(ROOT, 'dist', 'grid-emu', 'gen');
const APPDIR = path.join(ROOT, 'dist', 'the_grid', 'source', 'javascript');
const GFXDIR = path.join(ROOT, 'kit', 'emu', 'web', 'gfx');
const OUT = path.resolve(process.argv[2] || path.join(ROOT, 'dist', 'grid-emu', 'index.html'));
const SEARCH = (process.env.NODE_PATH || '').split(path.delimiter).filter(Boolean).concat([ROOT, HERE]);
const resolve = (m) => require.resolve(m, { paths: SEARCH });
const req = (m) => require(resolve(m));
req.resolve = resolve;
const esbuild = req('esbuild');

// 1. the app as the car builds it (the staged tree, no SDK)
execFileSync('python3', [path.join(ROOT, 'kit', 'tools', 'build.py'), 'the_grid', '--preview-only'], { stdio: 'inherit', cwd: ROOT });
fs.mkdirSync(GEN, { recursive: true });

// 2. the real Settings class and settings wiring, from the app's own kit/mgu.js (as kit/tools/hu-stub.js takes them)
const mgu = fs.readFileSync(path.join(APPDIR, 'kit', 'mgu.js'), 'utf8').replace(/\r\n/g, '\n');
const cls = mgu.match(/class Settings[\s\S]*?\n}\n/), wire = mgu.match(/function wireSettings[\s\S]*?\n}\n/);
if (!cls || !wire) throw new Error('kit/mgu.js: Settings / wireSettings not found');
fs.writeFileSync(path.join(GEN, 'mgu-parts.js'), "'use strict';\n// generated by kit/tools/grid_emu/build.js from the app's kit/mgu.js\n" +
    'module.exports = function (fs, path, DATA_DIR, log, SPEC, listSheet) {\n' + cls[0] + wire[0] + 'return { Settings, wireSettings };\n};\n');

// 3. the files the app reads at run time: its glyph atlases
const files = {};
const fontDir = path.join(APPDIR, 'kit', 'fonts');
fs.readdirSync(fontDir).filter((f) => /\.json$/.test(f) && !/^(cjk|korean|cyrillic)\.json$/.test(f)).forEach((f) => {
    files['/app/kit/fonts/' + f] = fs.readFileSync(path.join(fontDir, f), 'utf8');
});
fs.writeFileSync(path.join(GEN, 'files.js'), 'module.exports = ' + JSON.stringify(files) + ';\n');
fs.writeFileSync(path.join(GEN, 'wasm.js'), 'module.exports = ' + JSON.stringify(fs.readFileSync(path.join(GFXDIR, 'mgu-gfx-wasm.wasm')).toString('base64')) + ';\n');
const spec = JSON.parse(fs.readFileSync(path.join(APPDIR, 'kit', 'app-spec.json'), 'utf8'));
let rev = '';
try { rev = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT }).toString().trim(); } catch (e) { /* not a checkout */ }
const dirty = (() => { try { return execFileSync('git', ['status', '--porcelain', 'apps/the_grid', 'kit/runtime'], { cwd: ROOT }).toString().trim() ? '+' : ''; } catch (e) { return ''; } })();
fs.writeFileSync(path.join(GEN, 'build.js'), 'module.exports = ' + JSON.stringify({ version: spec.version, rev: rev + dirty, built: new Date().toISOString() }) + ';\n');

// 4. the bundle
const shim = (f) => path.join(WEB, 'shims', f);
const plugin = {
    name: 'grid-emu',
    setup(b) {
        const map = { fs: shim('fs.js'), net: shim('net.js'), zlib: shim('zlib.js'), someip: shim('missing.js'), 'oap-sdk': shim('missing.js'),
            path: req.resolve('path-browserify'), events: req.resolve('events/'), buffer: req.resolve('buffer/'), assert: shim('missing.js'),
            child_process: shim('missing.js'), os: shim('missing.js'), crypto: shim('missing.js') };
        b.onResolve({ filter: /^(fs|net|zlib|someip|oap-sdk|path|events|buffer|assert|child_process|os|crypto)$/ }, (a) => ({ path: map[a.path] }));
        const withExt = (p) => (fs.existsSync(p) && fs.statSync(p).isFile() ? p : fs.existsSync(p + '.js') ? p + '.js' : p);
        b.onResolve({ filter: /^APPDIR\// }, (a) => ({ path: withExt(path.join(APPDIR, a.path.slice(7))) }));
        b.onResolve({ filter: /^GEN\// }, (a) => ({ path: path.join(GEN, a.path.slice(4)) + (/\.js$/.test(a.path) ? '' : '.js') }));
        b.onResolve({ filter: /^GFXDIR\// }, (a) => ({ path: path.join(GFXDIR, a.path.slice(7)) }));
        // the app's require('./kit/mgu') is the page's head unit
        b.onResolve({ filter: /kit[\\/]mgu$/ }, (a) => (a.importer.indexOf(APPDIR) === 0 ? { path: path.join(WEB, 'mgu-stub.js') } : undefined));
        // Node's __dirname / __filename for the app's modules, as on the car (/app = source/javascript)
        b.onLoad({ filter: /\.js$/ }, (a) => {
            if (a.path.indexOf(APPDIR) !== 0) return undefined;
            const rel = path.relative(APPDIR, a.path).split(path.sep).join('/');
            const dir = '/app' + (path.dirname(rel) === '.' ? '' : '/' + path.dirname(rel));
            return { contents: 'var __dirname = ' + JSON.stringify(dir) + ', __filename = ' + JSON.stringify('/app/' + rel) + ';\n' + fs.readFileSync(a.path, 'utf8'), loader: 'js', resolveDir: path.dirname(a.path) };
        });
    },
};
(async () => {
    const r = await esbuild.build({
        entryPoints: [path.join(WEB, 'main.js')], bundle: true, write: false, platform: 'browser', format: 'iife', target: ['es2020'],
        inject: [shim('globals.js')], plugins: [plugin], minify: !process.env.GRID_EMU_DEBUG, logLevel: 'warning', legalComments: 'none',
        define: { 'process.env.MGU_DEBUG': 'undefined', global: 'globalThis' },
        nodePaths: (process.env.NODE_PATH || '').split(path.delimiter).filter(Boolean),
    });
    const js = r.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
    fs.writeFileSync(path.join(GEN, 'bundle.js'), js);
    // 5. the page: markup, styles (with the OFL fonts the page chrome uses), the bundle
    const font = (name, file) => "@font-face { font-family: '" + name + "'; src: url(data:font/ttf;base64," +
        fs.readFileSync(path.join(ROOT, 'kit', 'fonts-src', 'grid', file)).toString('base64') + ") format('truetype'); font-display: swap; }";
    const css = fs.readFileSync(path.join(WEB, 'page.css'), 'utf8').replace('/*FONTS*/', () => font('Orbitron', 'Orbitron-wght.ttf') + '\n' + font('ShareTech', 'ShareTechMono-Regular.ttf'));
    const html = fs.readFileSync(path.join(WEB, 'page.html'), 'utf8').replace('/*CSS*/', () => css).replace('/*JS*/', () => js);
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, html);
    console.log('grid-emu: ' + path.relative(process.cwd(), OUT) + ' (' + Math.round(html.length / 1024) + ' KiB, The Grid ' + spec.version + (rev ? ' @ ' + rev + dirty : '') + ')');
})().catch((e) => { console.error(e); process.exit(1); });
